CREATE TABLE public.mitra (
    id_mitra integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_mitra varchar(150) NOT NULL UNIQUE,
    nama_penanggung_jawab varchar(100),
    no_hp varchar(20),
    alamat_mitra varchar(255) NOT NULL,
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    dibuat_oleh integer,
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    diubah_oleh integer,
    diubah_pada timestamptz,
    is_deleted integer NOT NULL DEFAULT 0,
    CONSTRAINT ck_mitra_deleted CHECK (is_deleted IN (0, 1) AND (is_deleted = 0 OR aktif = 0)),
    CONSTRAINT ck_mitra_audit CHECK ((diubah_oleh IS NULL) = (diubah_pada IS NULL))
);

CREATE TABLE public.pengguna (
    id_pengguna integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama varchar(100) NOT NULL,
    email varchar(150) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    no_hp varchar(20),
    peran integer NOT NULL CHECK (peran IN (1, 2, 3, 4, 5)),
    id_mitra integer,
    nama_usaha varchar(150),
    alamat varchar(255),
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    dibuat_oleh integer,
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    diubah_oleh integer,
    diubah_pada timestamptz,
    is_deleted integer NOT NULL DEFAULT 0,
    CONSTRAINT ck_pengguna_afiliasi CHECK (
        (peran IN (1, 2, 3) AND id_mitra IS NULL AND nullif(btrim(alamat), '') IS NOT NULL)
        OR (peran = 4 AND id_mitra IS NULL)
        OR (peran = 5 AND id_mitra IS NOT NULL)
    ),
    CONSTRAINT ck_pengguna_deleted CHECK (is_deleted IN (0, 1) AND (is_deleted = 0 OR aktif = 0)),
    CONSTRAINT ck_pengguna_audit CHECK ((diubah_oleh IS NULL) = (diubah_pada IS NULL))
);

CREATE TABLE public.drop_point (
    id_drop_point integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_drop_point varchar(100) NOT NULL UNIQUE,
    alamat varchar(255) NOT NULL,
    latitude numeric(9, 6),
    longitude numeric(9, 6),
    jam_operasional varchar(200) NOT NULL,
    nama_komunitas varchar(20),
    kontak_komunitas varchar(20),
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    dibuat_oleh integer,
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    diubah_oleh integer,
    diubah_pada timestamptz,
    is_deleted integer NOT NULL DEFAULT 0,
    CONSTRAINT ck_dp_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_dp_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_dp_koordinat CHECK ((latitude IS NULL) = (longitude IS NULL)),
    CONSTRAINT ck_dp_komunitas CHECK (kontak_komunitas IS NULL OR nullif(btrim(nama_komunitas), '') IS NOT NULL),
    CONSTRAINT ck_dp_deleted CHECK (is_deleted IN (0, 1) AND (is_deleted = 0 OR aktif = 0)),
    CONSTRAINT ck_dp_audit CHECK ((diubah_oleh IS NULL) = (diubah_pada IS NULL))
);

CREATE TABLE public.jenis_sampah (
    id_jenis_sampah integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_jenis varchar(50) NOT NULL UNIQUE,
    ketentuan varchar(500) NOT NULL,
    poin_per_kg numeric(10, 2) NOT NULL CHECK (poin_per_kg >= 0),
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    dibuat_oleh integer,
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    diubah_oleh integer,
    diubah_pada timestamptz,
    is_deleted integer NOT NULL DEFAULT 0,
    CONSTRAINT ck_js_jenis CHECK (nama_jenis IN ('Plastik', 'Kardus', 'Kaca', 'Logam')),
    CONSTRAINT ck_js_deleted CHECK (is_deleted IN (0, 1) AND (is_deleted = 0 OR aktif = 0)),
    CONSTRAINT ck_js_audit CHECK ((diubah_oleh IS NULL) = (diubah_pada IS NULL))
);

CREATE TABLE public.slot_jemput (
    id_slot integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mulai_pada timestamptz NOT NULL,
    selesai_pada timestamptz NOT NULL,
    kapasitas integer NOT NULL CHECK (kapasitas > 0),
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    dibuat_oleh integer NOT NULL,
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_slot_waktu UNIQUE (mulai_pada, selesai_pada),
    CONSTRAINT ck_slot_waktu CHECK (selesai_pada > mulai_pada)
);

CREATE TABLE public.setoran (
    id_setoran integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna integer NOT NULL,
    id_drop_point integer NOT NULL,
    status integer NOT NULL CHECK (status IN (1, 2, 3, 4, 5)),
    waktu_timbang timestamptz,
    foto_bukti varchar(255),
    status_drop_point integer NOT NULL DEFAULT 1 CHECK (status_drop_point IN (1, 2, 3)),
    waktu_terima_drop_point timestamptz,
    catatan_serah_terima varchar(500),
    dibuat_oleh integer NOT NULL,
    ditimbang_oleh integer,
    diverifikasi_oleh integer,
    waktu_verifikasi timestamptz,
    catatan_verifikasi varchar(500),
    diterima_oleh integer,
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    CONSTRAINT ck_setoran_timbang CHECK (
        status NOT IN (2, 3, 4) OR
        (waktu_timbang IS NOT NULL AND ditimbang_oleh IS NOT NULL AND nullif(btrim(foto_bukti), '') IS NOT NULL)
    ),
    CONSTRAINT ck_setoran_verifikasi CHECK (
        status NOT IN (3, 4) OR (diverifikasi_oleh IS NOT NULL AND waktu_verifikasi IS NOT NULL)
    ),
    CONSTRAINT ck_setoran_tolak CHECK (status <> 4 OR nullif(btrim(catatan_verifikasi), '') IS NOT NULL),
    CONSTRAINT ck_setoran_penerimaan CHECK (
        status_drop_point = 1 OR (diterima_oleh IS NOT NULL AND waktu_terima_drop_point IS NOT NULL)
    ),
    CONSTRAINT ck_setoran_selisih CHECK (
        status_drop_point <> 2 OR nullif(btrim(catatan_serah_terima), '') IS NOT NULL
    )
);

CREATE TABLE public.penjemputan (
    id_penjemputan integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_setoran integer NOT NULL UNIQUE,
    id_slot integer NOT NULL,
    id_petugas integer,
    alamat_jemput varchar(255) NOT NULL,
    petunjuk_lokasi varchar(225) NOT NULL,
    catatan_perkiraan varchar(500),
    potongan_persen_disepakati numeric(5, 2) NOT NULL DEFAULT 0
        CHECK (potongan_persen_disepakati BETWEEN 0 AND 100),
    status varchar(20) NOT NULL
        CHECK (status IN ('DIAJUKAN', 'DIJADWALKAN', 'DALAM_PERJALANAN', 'SELESAI', 'GAGAL', 'DIBATALKAN')),
    alasan_gagal varchar(255),
    waktu_pengambilan timestamptz,
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    dibuat_oleh integer NOT NULL,
    CONSTRAINT ck_jemput_petugas CHECK (status IN ('DIAJUKAN', 'DIBATALKAN') OR id_petugas IS NOT NULL),
    CONSTRAINT ck_jemput_gagal CHECK (status <> 'GAGAL' OR nullif(btrim(alasan_gagal), '') IS NOT NULL),
    CONSTRAINT ck_jemput_lokasi CHECK (
        nullif(btrim(alamat_jemput), '') IS NOT NULL AND nullif(btrim(petunjuk_lokasi), '') IS NOT NULL
    )
);

CREATE TABLE public.pencairan_poin (
    id_pencairan integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna integer NOT NULL,
    jumlah_poin bigint NOT NULL CHECK (jumlah_poin > 0),
    nilai_rupiah_per_poin_snapshot numeric(18, 2) NOT NULL
        CHECK (nilai_rupiah_per_poin_snapshot > 0),
    nama_bank varchar(50) NOT NULL,
    nomor_rekening varchar(30) NOT NULL,
    nama_pemilik_rekening varchar(100) NOT NULL,
    status integer NOT NULL CHECK (status IN (1, 2, 3, 4, 5)),
    diproses_oleh integer,
    diproses_pada timestamptz,
    alasan_penolakan varchar(255),
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    dibuat_oleh integer NOT NULL,
    CONSTRAINT ck_cair_proses CHECK (
        status NOT IN (2, 3, 4) OR (diproses_oleh IS NOT NULL AND diproses_pada IS NOT NULL)
    ),
    CONSTRAINT ck_cair_tolak CHECK (status <> 4 OR nullif(btrim(alasan_penolakan), '') IS NOT NULL)
);

CREATE TABLE public.penjualan (
    id_penjualan integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_drop_point integer NOT NULL,
    id_mitra integer NOT NULL,
    tanggal_penjualan date NOT NULL,
    waktu_pengiriman timestamptz,
    dikonfirmasi_oleh integer,
    waktu_terima_mitra timestamptz,
    status varchar(10) NOT NULL
        CHECK (status IN ('DRAFT', 'DIKIRIM', 'DITERIMA', 'SELESAI', 'DIBATALKAN')),
    catatan varchar(500),
    dibuat_oleh integer NOT NULL,
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    CONSTRAINT ck_jual_kirim CHECK (status NOT IN ('DIKIRIM', 'DITERIMA', 'SELESAI') OR waktu_pengiriman IS NOT NULL),
    CONSTRAINT ck_jual_terima CHECK (
        status NOT IN ('DITERIMA', 'SELESAI') OR
        (dikonfirmasi_oleh IS NOT NULL AND waktu_terima_mitra IS NOT NULL
         AND waktu_terima_mitra >= waktu_pengiriman)
    )
);

CREATE TABLE public.mutasi_kas (
    id_mutasi_kas integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pos_dana varchar(20) NOT NULL
        CHECK (pos_dana IN ('HASIL_PENJUALAN', 'CADANGAN_POIN', 'KOMUNITAS', 'OPERASIONAL')),
    jumlah_rupiah numeric(18, 2) NOT NULL CHECK (jumlah_rupiah <> 0),
    id_penjualan integer,
    id_pencairan integer,
    metode varchar(20) NOT NULL CHECK (metode IN ('TRANSFER', 'TUNAI')),
    pihak_terkait varchar(150),
    bukti varchar(255) NOT NULL CHECK (nullif(btrim(bukti), '') IS NOT NULL),
    keterangan varchar(255),
    persen_cadangan_snapshot numeric(5, 2),
    persen_komunitas_snapshot numeric(5, 2),
    waktu_transaksi timestamptz NOT NULL,
    dibuat_oleh integer NOT NULL,
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_kas_satu_ref CHECK (id_penjualan IS NULL OR id_pencairan IS NULL),
    CONSTRAINT ck_kas_penerimaan CHECK (
        (pos_dana = 'HASIL_PENJUALAN' AND id_penjualan IS NOT NULL AND jumlah_rupiah > 0
         AND persen_cadangan_snapshot IS NOT NULL AND persen_komunitas_snapshot IS NOT NULL
         AND persen_cadangan_snapshot BETWEEN 0 AND 100
         AND persen_komunitas_snapshot BETWEEN 0 AND 100
         AND persen_cadangan_snapshot + persen_komunitas_snapshot <= 100)
        OR (pos_dana <> 'HASIL_PENJUALAN' AND id_penjualan IS NULL
            AND persen_cadangan_snapshot IS NULL AND persen_komunitas_snapshot IS NULL)
    ),
    CONSTRAINT ck_kas_pembayaran CHECK (
        id_pencairan IS NULL OR
        (pos_dana = 'CADANGAN_POIN' AND jumlah_rupiah < 0 AND metode = 'TRANSFER')
    ),
    CONSTRAINT ck_kas_komunitas CHECK (
        pos_dana <> 'KOMUNITAS' OR
        (jumlah_rupiah < 0 AND nullif(btrim(pihak_terkait), '') IS NOT NULL)
    ),
    CONSTRAINT ck_kas_tanpa_ref CHECK (
        id_penjualan IS NOT NULL OR id_pencairan IS NOT NULL OR
        (nullif(btrim(pihak_terkait), '') IS NOT NULL AND nullif(btrim(keterangan), '') IS NOT NULL)
    )
);

CREATE TABLE public.detail_setoran (
    id_detail_setoran integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_setoran integer NOT NULL,
    id_jenis_sampah integer NOT NULL,
    berat_diterima_kg numeric(12, 3),
    berat_ditolak_kg numeric(12, 3),
    alasan_penolakan varchar(255),
    poin_per_kg_snapshot numeric(10, 2) NOT NULL CHECK (poin_per_kg_snapshot >= 0),
    berat_masuk_drop_point_kg numeric(12, 3)
        CHECK (berat_masuk_drop_point_kg IS NULL OR berat_masuk_drop_point_kg >= 0),
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    dibuat_oleh integer NOT NULL,
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_dsetoran_jenis UNIQUE (id_setoran, id_jenis_sampah),
    CONSTRAINT ck_dsetoran_berat CHECK (
        (berat_diterima_kg IS NULL AND berat_ditolak_kg IS NULL) OR
        (berat_diterima_kg IS NOT NULL AND berat_ditolak_kg IS NOT NULL
         AND berat_diterima_kg >= 0 AND berat_ditolak_kg >= 0
         AND berat_diterima_kg + berat_ditolak_kg > 0)
    ),
    CONSTRAINT ck_dsetoran_alasan CHECK (
        berat_ditolak_kg IS NULL OR berat_ditolak_kg = 0 OR
        nullif(btrim(alasan_penolakan), '') IS NOT NULL
    )
);

CREATE TABLE public.detail_penjualan (
    id_detail_penjualan integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_penjualan integer NOT NULL,
    id_jenis_sampah integer NOT NULL,
    berat_dikirim_kg numeric(12, 3) NOT NULL CHECK (berat_dikirim_kg > 0),
    berat_diterima_kg numeric(12, 3),
    berat_ditolak_kg numeric(12, 3),
    harga_per_kg_snapshot numeric(18, 2) NOT NULL CHECK (harga_per_kg_snapshot >= 0),
    alasan_penolakan varchar(255),
    catatan_selisih_timbang varchar(255),
    berat_retur_kembali_kg numeric(12, 3) NOT NULL DEFAULT 0,
    waktu_retur_kembali timestamptz,
    aktif integer NOT NULL DEFAULT 1 CHECK (aktif IN (0, 1)),
    dibuat_oleh integer NOT NULL,
    dibuat_pada timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_djual_jenis UNIQUE (id_penjualan, id_jenis_sampah),
    CONSTRAINT ck_djual_berat CHECK (
        (berat_diterima_kg IS NULL AND berat_ditolak_kg IS NULL) OR
        (berat_diterima_kg IS NOT NULL AND berat_ditolak_kg IS NOT NULL
         AND berat_diterima_kg >= 0 AND berat_ditolak_kg >= 0)
    ),
    CONSTRAINT ck_djual_alasan CHECK (
        berat_ditolak_kg IS NULL OR berat_ditolak_kg = 0 OR
        nullif(btrim(alasan_penolakan), '') IS NOT NULL
    ),
    CONSTRAINT ck_djual_selisih CHECK (
        berat_diterima_kg IS NULL OR
        berat_diterima_kg + berat_ditolak_kg = berat_dikirim_kg OR
        nullif(btrim(catatan_selisih_timbang), '') IS NOT NULL
    ),
    CONSTRAINT ck_djual_retur CHECK (
        berat_retur_kembali_kg >= 0 AND
        (berat_retur_kembali_kg = 0 OR
         (berat_ditolak_kg IS NOT NULL AND berat_retur_kembali_kg <= berat_ditolak_kg))
    ),
    CONSTRAINT ck_djual_retur_waktu CHECK (
        (berat_retur_kembali_kg = 0 AND waktu_retur_kembali IS NULL) OR
        (berat_retur_kembali_kg > 0 AND waktu_retur_kembali IS NOT NULL)
    )
);

